#!/usr/bin/env python3
"""Export the staged Rust bring-up driver as the kernel aport's extra patch.

Run stage.py first, inside pmport. The base must be out/linux HEAD, as used
by the isolated source snapshot. Existing sm6450 patches are not rewritten.
"""
import argparse
import difflib
from pathlib import Path
import subprocess

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('tree', type=Path)
args = parser.parse_args()
root = Path(__file__).resolve().parents[2]
existing = ['rust/kernel/lib.rs', 'rust/bindings/bindings_helper.h',
            'drivers/misc/Kconfig', 'drivers/misc/Makefile',
            'arch/arm64/boot/dts/qcom/sm6450-sony-xperia-columbia-pdx246.dts']
added = ['rust/kernel/egis_gpio.rs', 'arch/arm64/boot/dts/qcom/pdx246-egisfp.dtsi']
added += [f'drivers/misc/egisfp/{name}' for name in
          ('egisfp.rs', 'eventfd.rs', 'egisfp.h', 'Kconfig', 'Makefile')]
result = ['Egis EC617 Rust hardware bring-up driver.\n',
          'Generated by kernel/egisfp/export.py; edit kernel/egisfp sources.\n\n']
for name in existing + added:
    old = subprocess.check_output(['git', '-C', str(root / 'out/linux'),
                                   'show', f'HEAD:{name}'], text=True) if name in existing else ''
    new = (args.tree / name).read_text()
    result.append(f'diff --git a/{name} b/{name}\n')
    result.extend(difflib.unified_diff(old.splitlines(keepends=True), new.splitlines(keepends=True),
                                     fromfile=f'a/{name}' if old else '/dev/null', tofile=f'b/{name}'))
path = root / 'aports/device/testing/linux-postmarketos-qcom-sm6450/bringup-egisfp-rust.patch'
path.write_text(''.join(result))
print(path)
