#!/bin/sh
# Export the mainline SM6450 work out of out/linux and into the repository.
#
# The kernel tree under out/ is a disposable depth-1 clone and is gitignored,
# which is right for a 6 GiB checkout and wrong for the only copy of the work.
# This writes the sm6450 branch out as a numbered patch series under
# kernel/patches/, which is both what git tracks and what an APKBUILD applies,
# so the two never drift.
#
#   scripts/sync-kernel-patches.sh            # export
#   scripts/sync-kernel-patches.sh --check    # fail if the export is stale
#
# Run it after every commit on the sm6450 branch. --check is what a Tier 0
# pass should call, so a build can never be made from a series that does not
# match the tree it was developed in.
set -eu

ROOT=$(cd "$(dirname "$0")/.." && pwd)
TREE=$ROOT/out/linux
OUT=$ROOT/kernel/patches
BRANCH=sm6450
BASE=${KERNEL_BASE:-}

if [ ! -d "$TREE/.git" ]; then
	echo "no kernel tree at $TREE; see docs/06-mainline.md for the clone" >&2
	exit 1
fi

cur=$(git -C "$TREE" branch --show-current)
if [ "$cur" != "$BRANCH" ]; then
	echo "out/linux is on '$cur', expected '$BRANCH'" >&2
	exit 1
fi

# The base is the upstream tag the branch forked from, so the series stays
# applicable to a fresh clone of the same stable line rather than to whatever
# happens to be checked out.
if [ -z "$BASE" ]; then
	BASE=$(git -C "$TREE" merge-base HEAD origin/linux-6.18.y)
fi
version=$(git -C "$TREE" describe --tags --abbrev=0 "$BASE" 2>/dev/null || echo "$BASE")

check=${1:-}
dest=$OUT
if [ "$check" = "--check" ]; then
	dest=$(mktemp -d)
	trap 'rm -rf "$dest"' EXIT
fi

mkdir -p "$dest"
# Clear stale numbers: a dropped or reordered commit would otherwise leave an
# orphan patch behind that the APKBUILD would still apply.
find "$dest" -maxdepth 1 -name '*.patch' -delete

git -C "$TREE" format-patch -q --no-signature --zero-commit --no-numbered \
	-o "$dest" "$BASE..HEAD" >/dev/null

{
	echo "# Generated by scripts/sync-kernel-patches.sh - do not edit."
	echo "#"
	echo "# Base: $version"
	echo "# Branch: $BRANCH in out/linux"
	echo "#"
	git -C "$TREE" log --reverse --format='%s' "$BASE..HEAD"
} > "$dest/SERIES"

if [ "$check" = "--check" ]; then
	if diff -r -q "$OUT" "$dest" >/dev/null 2>&1; then
		echo "==> kernel/patches is up to date with out/linux"
	else
		echo "==> kernel/patches is stale; run scripts/sync-kernel-patches.sh" >&2
		diff -r -q "$OUT" "$dest" >&2 || true
		exit 1
	fi
	exit 0
fi

echo "==> base $version"
ls -1 "$OUT"/*.patch | while read -r p; do
	printf '    %-58s %s lines\n' "$(basename "$p")" "$(wc -l < "$p")"
done
