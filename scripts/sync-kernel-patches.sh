#!/bin/sh
# Export the kernel work out of out/linux and into the repository.
#
# The kernel tree under out/ is a disposable depth-1 clone and is gitignored,
# which is right for a 6 GiB checkout and wrong for the only copy of the work.
# The work is three layers of commits on the stable base, each a branch that
# the next one builds on:
#
# - backports: upstream commits and postings the base predates. They are not
#   ours; each keeps its author and says where it came from.
# - sm6450: the series for upstream, the SoC and the board, as it goes to the
#   lists.
# - pdx246: bring-up that never goes upstream as is: workarounds,
#   development drivers, the bootloader's ids. Each commit says why.
#
# pdx246 is the kernel that gets built. This writes each layer out twice,
# because the two readers want different things:
#
# - kernel/backports/, kernel/patches/ and kernel/bringup/, one patch per
#   commit, the form the work is read, reviewed and posted in.
#   kernel/patches/ is the series alone.
# - the kernel aport, one squashed diff per layer, so that its source= and
#   checksums change only when a layer does, and what is not for upstream
#   stays visibly apart from what is.
#
# All of it comes from the same tree in the same run, so the copies cannot
# disagree about what the kernel is.
#
#   scripts/sync-kernel-patches.sh            # export
#   scripts/sync-kernel-patches.sh --check    # fail if any export is stale
#
# Run it after every kernel commit, then scripts/pmb checksum on the aport.
set -eu

ROOT=$(cd "$(dirname "$0")/.." && pwd)
TREE=$ROOT/out/linux
APORT=$ROOT/aports/device/testing/linux-postmarketos-qcom-sm6450

# Branch, directory under kernel/, and squashed patch in the aport, in the
# order they apply.
LAYERS="backports:backports:backports.patch
sm6450:patches:sm6450-mainline.patch
pdx246:bringup:pdx246-bringup.patch"

if [ ! -d "$TREE/.git" ]; then
	echo "no kernel tree at $TREE; see docs/06-mainline.md for the clone" >&2
	exit 1
fi

# The base is the upstream tag the work forked from, so every layer stays
# applicable to a fresh clone of the same stable line.
BASE=${KERNEL_BASE:-$(git -C "$TREE" merge-base pdx246 origin/linux-6.18.y)}
version=$(git -C "$TREE" describe --tags --abbrev=0 "$BASE" 2>/dev/null || echo "$BASE")

check=${1:-}
work=$ROOT/kernel
squashdir=$APORT
if [ "$check" = "--check" ]; then
	tmp=$(mktemp -d)
	trap 'rm -rf "$tmp"' EXIT
	work=$tmp/kernel
	squashdir=$tmp/aport
	mkdir -p "$squashdir"
fi

prev=$BASE
rc=0
echo "$LAYERS" | while IFS=: read -r branch dir squash; do
	if ! git -C "$TREE" merge-base --is-ancestor "$prev" "$branch"; then
		echo "$branch does not build on $prev" >&2
		exit 1
	fi
	count=$(git -C "$TREE" rev-list --count "$prev..$branch")
	if [ "$count" -eq 0 ]; then
		echo "$branch adds nothing to $prev; drop the layer" >&2
		exit 1
	fi

	dest=$work/$dir
	mkdir -p "$dest"
	# Clear stale numbers: a dropped or reordered commit would otherwise
	# leave an orphan patch behind.
	find "$dest" -maxdepth 1 -name '*.patch' -delete
	git -C "$TREE" format-patch -q --no-signature --zero-commit \
		--no-numbered -o "$dest" "$prev..$branch" >/dev/null
	{
		echo "# Generated by scripts/sync-kernel-patches.sh - do not edit."
		echo "#"
		echo "# Base: $version"
		echo "# Branch: $branch in out/linux, on $(git -C "$TREE" rev-parse --short "$prev")"
		echo "#"
		git -C "$TREE" log --reverse --format='%s' "$prev..$branch"
	} > "$dest/SERIES"

	# git diff emits no header of its own, and patch(1) ignores everything
	# before the first "diff --git", so the provenance goes at the top.
	{
		echo "Generated by scripts/sync-kernel-patches.sh - do not edit."
		echo
		echo "The $branch branch squashed into one diff, for the kernel aport"
		echo "to apply. kernel/$dir/ has the same change as $count separate"
		echo "commits with their reasoning; read that one, not this one."
		echo
		echo "Base: $version"
		echo
		git -C "$TREE" diff --no-ext-diff --stat "$prev..$branch" | sed 's/^/    /'
		echo
		git -C "$TREE" diff --no-ext-diff "$prev..$branch"
	} > "$squashdir/$squash"

	if [ "$check" = "--check" ]; then
		if ! diff -r -q "$ROOT/kernel/$dir" "$dest" >/dev/null 2>&1 ||
		   ! cmp -s "$APORT/$squash" "$squashdir/$squash"; then
			echo "==> $branch is stale; run scripts/sync-kernel-patches.sh" >&2
			diff -r -q "$ROOT/kernel/$dir" "$dest" >&2 || true
			exit 1
		fi
		echo "==> $branch is up to date"
	else
		printf '==> %-10s %3s commits, kernel/%s/ and %s\n' \
			"$branch" "$count" "$dir" "$squash"
	fi
	prev=$branch
done || rc=$?

[ "$check" = "--check" ] || [ "$rc" -ne 0 ] ||
	echo "==> run 'scripts/pmb checksum linux-postmarketos-qcom-sm6450' next"
exit $rc
