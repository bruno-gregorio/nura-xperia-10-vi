#!/bin/sh
# Export the mainline SM6450 work out of out/linux and into the repository.
#
# The kernel tree under out/ is a disposable depth-1 clone and is gitignored,
# which is right for a 6 GiB checkout and wrong for the only copy of the work.
# This writes the sm6450 branch out twice, because the two readers want
# different things:
#
# - kernel/patches/, a numbered series with one patch per commit. That is the
#   form the work is meant to be read and reviewed in, and the form it will be
#   posted to the lists in, so it is the one git tracks commit by commit.
# - the kernel aport, as a single squashed diff. An APKBUILD that listed
#   twenty-odd patches would need its source= and its twenty-odd checksums
#   rewritten on every kernel commit, which is churn in a hand-written file
#   for no gain: abuild does not care how the diff is divided, and a build
#   failure in generated driver code is not easier to read for being split.
#   One file means one source line and one checksum.
#
# Both come from the same range in the same tree on the same run, so they
# cannot disagree about what the kernel is.
#
#   scripts/sync-kernel-patches.sh            # export
#   scripts/sync-kernel-patches.sh --check    # fail if either export is stale
#
# Run it after every commit on the sm6450 branch, then scripts/pmb checksum
# on the aport. --check is what a Tier 0 pass should call, so a build can
# never be made from a series that does not match the tree it was developed
# in.
set -eu

ROOT=$(cd "$(dirname "$0")/.." && pwd)
TREE=$ROOT/out/linux
OUT=$ROOT/kernel/patches
APORT=$ROOT/aports/device/testing/linux-postmarketos-qcom-sm6450
SQUASH=sm6450-mainline.patch
BRANCH=sm6450
BASE=${KERNEL_BASE:-}

if [ ! -d "$TREE/.git" ]; then
	echo "no kernel tree at $TREE; see docs/06-mainline.md for the clone" >&2
	exit 1
fi

cur=$(git -C "$TREE" branch --show-current)
if [ "$cur" != "$BRANCH" ]; then
	echo "out/linux is on '$cur', expected '$BRANCH'" >&2
	exit 1
fi

# The base is the upstream tag the branch forked from, so the series stays
# applicable to a fresh clone of the same stable line rather than to whatever
# happens to be checked out.
if [ -z "$BASE" ]; then
	BASE=$(git -C "$TREE" merge-base HEAD origin/linux-6.18.y)
fi
version=$(git -C "$TREE" describe --tags --abbrev=0 "$BASE" 2>/dev/null || echo "$BASE")

check=${1:-}
dest=$OUT
squashdir=$APORT
if [ "$check" = "--check" ]; then
	tmp=$(mktemp -d)
	trap 'rm -rf "$tmp"' EXIT
	dest=$tmp/patches
	squashdir=$tmp/aport
	mkdir -p "$dest" "$squashdir"
fi

mkdir -p "$dest"
# Clear stale numbers: a dropped or reordered commit would otherwise leave an
# orphan patch behind that the APKBUILD would still apply.
find "$dest" -maxdepth 1 -name '*.patch' -delete

git -C "$TREE" format-patch -q --no-signature --zero-commit --no-numbered \
	-o "$dest" "$BASE..HEAD" >/dev/null

{
	echo "# Generated by scripts/sync-kernel-patches.sh - do not edit."
	echo "#"
	echo "# Base: $version"
	echo "# Branch: $BRANCH in out/linux"
	echo "#"
	git -C "$TREE" log --reverse --format='%s' "$BASE..HEAD"
} > "$dest/SERIES"

# The squashed diff for the aport. git diff emits no header of its own, and
# patch(1) ignores everything before the first "diff --git", so the provenance
# can be written straight into the top of the file where anyone opening it
# will see it.
{
	echo "Generated by scripts/sync-kernel-patches.sh - do not edit."
	echo
	echo "The whole SM6450 series squashed into one diff, for the kernel"
	echo "aport to apply. kernel/patches/ has the same change as $(git -C "$TREE" rev-list --count "$BASE..HEAD") separate"
	echo "commits with their reasoning; read that one, not this one."
	echo
	echo "Base: $version"
	echo
	git -C "$TREE" diff --no-ext-diff --stat "$BASE..HEAD" | sed 's/^/    /'
	echo
	git -C "$TREE" diff --no-ext-diff "$BASE..HEAD"
} > "$squashdir/$SQUASH"

if [ "$check" = "--check" ]; then
	rc=0
	if diff -r -q "$OUT" "$dest" >/dev/null 2>&1; then
		echo "==> kernel/patches is up to date with out/linux"
	else
		echo "==> kernel/patches is stale; run scripts/sync-kernel-patches.sh" >&2
		diff -r -q "$OUT" "$dest" >&2 || true
		rc=1
	fi
	if cmp -s "$APORT/$SQUASH" "$squashdir/$SQUASH"; then
		echo "==> $SQUASH is up to date with out/linux"
	else
		echo "==> $SQUASH is stale; run scripts/sync-kernel-patches.sh" >&2
		rc=1
	fi
	exit $rc
fi

echo "==> base $version"
ls -1 "$OUT"/*.patch | while read -r p; do
	printf '    %-58s %s lines\n' "$(basename "$p")" "$(wc -l < "$p")"
done
printf '    %-58s %s lines\n' "$SQUASH (in the aport)" \
	"$(wc -l < "$APORT/$SQUASH")"
echo "==> run 'scripts/pmb checksum linux-postmarketos-qcom-sm6450' next"
